CREATE TABLE lessons
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id UUID    NOT NULL DEFAULT gen_random_uuid(),
    rider_id    BIGINT  NOT NULL,
    lesson_date DATE    NOT NULL,
    lesson_time TIME    NOT NULL,
    duration    INTEGER NOT NULL,

    CONSTRAINT uk_lessons_external_id UNIQUE (external_id),
    CONSTRAINT fk_lessons_rider FOREIGN KEY (rider_id) REFERENCES riders (id),
    CONSTRAINT ck_lessons_duration_positive CHECK (duration > 0)
);

CREATE INDEX idx_lessons_rider_id ON lessons (rider_id);
